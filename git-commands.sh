# Commit commands
git add .                               # Добавить индексацию
git commit -m "Diskription"             # Добваить описание 
git push                                # Отправить измения в данный репозиторий

git pull                                # Слить измения из удалённого репозитория 

# Branch commands
git branch -m old-branch new-branch     # Изменить ветку 
git switch                              # Переключиться на другую ветку   
